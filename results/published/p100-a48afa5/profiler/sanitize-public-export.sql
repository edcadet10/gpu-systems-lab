BEGIN IMMEDIATE;

DELETE FROM StringIds
WHERE id NOT IN (
    SELECT nameId FROM CUPTI_ACTIVITY_KIND_RUNTIME
    UNION
    SELECT demangledName FROM CUPTI_ACTIVITY_KIND_KERNEL
    UNION
    SELECT shortName FROM CUPTI_ACTIVITY_KIND_KERNEL
    UNION
    SELECT mangledName FROM CUPTI_ACTIVITY_KIND_KERNEL WHERE mangledName IS NOT NULL
    UNION
    SELECT textId FROM NVTX_EVENTS WHERE textId IS NOT NULL
    UNION
    SELECT jsonTextId FROM NVTX_EVENTS WHERE jsonTextId IS NOT NULL
);

COMMIT;
